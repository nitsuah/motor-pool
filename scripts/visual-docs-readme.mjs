#!/usr/bin/env node
/**
 * Rewrite the README's visual-docs block from what's on disk, so diagrams and
 * screenshots are embedded and linked by name and path every time CI
 * regenerates them. Zero dependencies — copy this file into any repo.
 *
 *   node scripts/visual-docs-readme.mjs            # rewrite README.md in place
 *   node scripts/visual-docs-readme.mjs --check    # exit 1 if README is out of date
 *
 * Scans   docs/diagrams/*.{svg,png}    (renders; .mmd / .excalidraw sources are linked)
 *         docs/screenshots/*.{png,jpg,jpeg,webp,gif}
 * Writes  between <!-- visual-docs:start --> and <!-- visual-docs:end --> in README.md.
 *         If the markers are missing, appends a new block at the end.
 *
 * Env: README (default README.md), DIAGRAMS_DIR, SCREENSHOTS_DIR.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, extname, join } from 'node:path';

const README = process.env.README ?? 'README.md';
const DIAGRAMS_DIR = process.env.DIAGRAMS_DIR ?? 'docs/diagrams';
const SCREENSHOTS_DIR = process.env.SCREENSHOTS_DIR ?? 'docs/screenshots';
const START = '<!-- visual-docs:start -->';
const END = '<!-- visual-docs:end -->';

const list = (dir, exts) =>
  existsSync(dir)
    ? readdirSync(dir).filter((f) => exts.includes(extname(f).toLowerCase())).sort().map((f) => join(dir, f).replace(/\\/g, '/'))
    : [];

/** File stem without extension(s): "flow.excalidraw.svg" -> "flow". */
const stem = (file) => basename(file).replace(/\.(excalidraw\.|drawio\.)?[^.]+$/i, '');

/** "pmo-open-work.png" -> "Pmo open work" */
const title = (file) => {
  const words = stem(file).replace(/[-_]+/g, ' ').trim();
  return words.charAt(0).toUpperCase() + words.slice(1);
};

const diagrams = list(DIAGRAMS_DIR, ['.svg', '.png']);
const sources = list(DIAGRAMS_DIR, ['.mmd', '.mermaid', '.excalidraw', '.drawio', '.d2']);
const screenshots = list(SCREENSHOTS_DIR, ['.png', '.jpg', '.jpeg', '.webp', '.gif']);

const lines = [START, '', '<!-- Generated by scripts/visual-docs-readme.mjs — edit the source files, not this block. -->', ''];
if (diagrams.length) {
  lines.push('### Diagrams', '');
  for (const d of diagrams) {
    const src = sources.find((s) => stem(s) === stem(d));
    lines.push(`**${title(d)}** — [\`${d}\`](./${d})${src ? ` · source [\`${src}\`](./${src})` : ''}`, '', `![${title(d)}](./${d})`, '');
  }
}
if (screenshots.length) {
  lines.push('### Screenshots', '');
  for (const s of screenshots) {
    lines.push(`**${title(s)}** — [\`${s}\`](./${s})`, '', `![${title(s)}](./${s})`, '');
  }
}
if (!diagrams.length && !screenshots.length) {
  lines.push(`_No diagrams in \`${DIAGRAMS_DIR}/\` or screenshots in \`${SCREENSHOTS_DIR}/\` yet._`, '');
}
lines.push(END);
const block = lines.join('\n');

const readme = existsSync(README) ? readFileSync(README, 'utf8') : '';
const eol = readme.includes('\r\n') ? '\r\n' : '\n';
const normalized = readme.replace(/\r\n/g, '\n');
const s = normalized.indexOf(START);
const e = normalized.indexOf(END);
const next = s !== -1 && e > s
  ? normalized.slice(0, s) + block + normalized.slice(e + END.length)
  : `${normalized.replace(/\n*$/, '\n')}\n## Screenshots & diagrams\n\n${block}\n`;

if (next === normalized) {
  console.log(`${README}: visual-docs block up to date (${diagrams.length} diagrams, ${screenshots.length} screenshots)`);
  process.exit(0);
}
if (process.argv.includes('--check')) {
  console.error(`${README}: visual-docs block is out of date — run node scripts/visual-docs-readme.mjs`);
  process.exit(1);
}
writeFileSync(README, next.replace(/\n/g, eol));
console.log(`${README}: visual-docs block updated (${diagrams.length} diagrams, ${screenshots.length} screenshots)`);
